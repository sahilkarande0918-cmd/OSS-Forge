"""Repository intelligence: languages, manifests, entry points, tests, CI, commands, symbols and import graph.

Results are cached per repository fingerprint (HEAD + size/mtime of every included file), so a second run
on an unchanged repository costs a stat() per file instead of a full parse.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import time
from collections import Counter, defaultdict
from dataclasses import asdict, dataclass, field
from pathlib import Path, PurePosixPath

from oss_forge.analysis.symbol_index import FileIndex, Symbol, index_file
from oss_forge.security.execution_policy import is_secret_file

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    tomllib = None

CACHE_VERSION = 3
MAX_FILE_BYTES = 1_000_000
IGNORED_DIRS = {".git", "node_modules", ".venv", "venv", "env", ".env", "__pycache__", "build", "dist", ".tox",
                ".nox", ".mypy_cache", ".pytest_cache", ".ruff_cache", "site-packages", "vendor", "vendors",
                "third_party", "third-party", ".next", ".nuxt", "coverage", "htmlcov", ".idea", ".vscode",
                ".eggs", "target", "out", ".gradle", "bower_components", ".oss-forge", ".cache", ".terraform"}
BINARY_SUFFIXES = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".zip", ".gz", ".tar", ".whl", ".so", ".dll",
                   ".exe", ".bin", ".pyc", ".class", ".jar", ".woff", ".woff2", ".ttf", ".mp4", ".mp3", ".db",
                   ".sqlite", ".parquet", ".npy", ".pkl", ".onnx", ".pt", ".lock"}
LANGUAGES = {".py": "Python", ".js": "JavaScript", ".jsx": "JavaScript", ".mjs": "JavaScript", ".cjs": "JavaScript",
             ".ts": "TypeScript", ".tsx": "TypeScript", ".go": "Go", ".rs": "Rust", ".java": "Java", ".rb": "Ruby",
             ".c": "C", ".h": "C", ".cpp": "C++", ".cc": "C++", ".cs": "C#", ".php": "PHP", ".kt": "Kotlin",
             ".swift": "Swift", ".sh": "Shell", ".md": "Markdown", ".toml": "TOML", ".yml": "YAML", ".yaml": "YAML",
             ".json": "JSON", ".html": "HTML", ".css": "CSS"}
CODE_LANGUAGES = {"Python", "JavaScript", "TypeScript", "Go", "Rust", "Java", "Ruby", "C", "C++", "C#", "PHP",
                  "Kotlin", "Swift", "Shell"}
MANIFESTS = {
    "pyproject.toml": "python", "setup.py": "python", "setup.cfg": "python", "requirements.txt": "pip",
    "Pipfile": "pipenv", "poetry.lock": "poetry", "uv.lock": "uv", "pdm.lock": "pdm", "environment.yml": "conda",
    "package.json": "npm", "package-lock.json": "npm", "yarn.lock": "yarn", "pnpm-lock.yaml": "pnpm",
    "bun.lockb": "bun", "Cargo.toml": "cargo", "go.mod": "go", "pom.xml": "maven", "build.gradle": "gradle",
    "build.gradle.kts": "gradle", "Gemfile": "bundler", "composer.json": "composer",
}
CI_PATTERNS = (".github/workflows/", ".gitlab-ci.yml", ".circleci/", "azure-pipelines.yml", "Jenkinsfile",
               ".travis.yml", "tox.ini", "noxfile.py", ".pre-commit-config.yaml", "bitbucket-pipelines.yml")
LINT_CONFIGS = {".flake8": "flake8", "ruff.toml": "ruff", ".ruff.toml": "ruff", ".pylintrc": "pylint",
                "mypy.ini": "mypy", ".eslintrc": "eslint", ".eslintrc.js": "eslint", ".eslintrc.json": "eslint",
                "eslint.config.js": "eslint", "eslint.config.mjs": "eslint", ".prettierrc": "prettier",
                ".prettierrc.json": "prettier", "biome.json": "biome", ".editorconfig": "editorconfig",
                "tsconfig.json": "tsc", ".pre-commit-config.yaml": "pre-commit"}
CONTRIB_PATTERNS = re.compile(r"(^|/)(CONTRIBUTING|CODE_OF_CONDUCT|DEVELOPMENT|HACKING)(\.\w+)?$|"
                              r"PULL_REQUEST_TEMPLATE|ISSUE_TEMPLATE", re.I)
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Code generated by", "autogenerated")


@dataclass
class RepoMap:
    root: str
    repo_id: str
    head: str | None
    branch: str | None
    remote: str | None
    fingerprint: str
    files: list[str] = field(default_factory=list)
    languages: dict[str, int] = field(default_factory=dict)          # language -> lines
    manifests: dict[str, str] = field(default_factory=dict)          # path -> ecosystem
    package_managers: list[str] = field(default_factory=list)
    entry_points: list[str] = field(default_factory=list)
    modules: dict[str, int] = field(default_factory=dict)            # top-level dir/package -> code files
    test_dirs: list[str] = field(default_factory=list)
    test_files: list[str] = field(default_factory=list)
    test_frameworks: list[str] = field(default_factory=list)
    test_command: list[str] = field(default_factory=list)
    ci_files: list[str] = field(default_factory=list)
    lint_tools: list[str] = field(default_factory=list)
    commands: dict[str, str] = field(default_factory=dict)           # name -> command string (from manifests)
    contribution_docs: list[str] = field(default_factory=list)
    symbols: list[dict] = field(default_factory=list)
    imports: dict[str, list[str]] = field(default_factory=dict)      # file -> internal files it imports
    string_literals: dict[str, list[str]] = field(default_factory=dict)
    parse_errors: dict[str, str] = field(default_factory=dict)
    total_tokens_estimate: int = 0
    skipped: dict[str, int] = field(default_factory=dict)
    build_seconds: float = 0.0
    cache_hit: bool = False

    # ---- helpers -------------------------------------------------------------------------------------
    def symbol_objects(self) -> list[Symbol]:
        return [Symbol(**s) for s in self.symbols]

    def imported_by(self) -> dict[str, list[str]]:
        rev: dict[str, list[str]] = defaultdict(list)
        for src, targets in self.imports.items():
            for t in targets:
                rev[t].append(src)
        return rev

    def to_dict(self) -> dict:
        return asdict(self)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2)

    def to_markdown(self, max_symbols: int = 40) -> str:
        code_langs = {k: v for k, v in self.languages.items() if k in CODE_LANGUAGES}
        hubs = sorted(self.imported_by().items(), key=lambda kv: -len(kv[1]))[:8]
        public = [s for s in self.symbols if not s["is_test"] and s["kind"] in ("class", "function")
                  and not s["name"].startswith("_")]
        lines = [
            f"# Repository map: {Path(self.root).name}",
            f"- HEAD: `{(self.head or 'n/a')[:12]}` on `{self.branch or 'n/a'}`  remote: {self.remote or 'n/a'}",
            f"- Files analysed: {len(self.files)} (~{self.total_tokens_estimate:,} tokens of text); "
            f"skipped: {self.skipped or 'none'}",
            "- Languages (lines): " + (", ".join(f"{k} {v:,}" for k, v in sorted(code_langs.items(), key=lambda kv: -kv[1])) or "none"),
            "- Package managers: " + (", ".join(self.package_managers) or "none detected"),
            "- Manifests: " + (", ".join(f"`{m}`" for m in self.manifests) or "none"),
            "- Entry points: " + (", ".join(f"`{e}`" for e in self.entry_points[:10]) or "none detected"),
            "- Modules: " + (", ".join(f"`{m}` ({n})" for m, n in sorted(self.modules.items(), key=lambda kv: -kv[1])[:12]) or "-"),
            "- Tests: " + (f"{len(self.test_files)} files in " + ", ".join(f"`{d}`" for d in self.test_dirs[:6])
                           if self.test_files else "none found")
            + f"; frameworks: {', '.join(self.test_frameworks) or 'unknown'}"
            + (f"; run: `{' '.join(self.test_command)}`" if self.test_command else ""),
            "- CI: " + (", ".join(f"`{c}`" for c in self.ci_files) or "none"),
            "- Lint/format: " + (", ".join(self.lint_tools) or "none detected"),
            "- Contribution docs: " + (", ".join(f"`{c}`" for c in self.contribution_docs) or "none"),
        ]
        if self.commands:
            lines.append("- Commands: " + "; ".join(f"{k}: `{v}`" for k, v in list(self.commands.items())[:10]))
        if hubs:
            lines.append("- Most-imported files: " + ", ".join(f"`{f}` ({len(srcs)})" for f, srcs in hubs))
        if self.parse_errors:
            lines.append(f"- Parse errors: {len(self.parse_errors)} file(s)")
        lines.append(f"\n## Public symbols ({len(public)} total, first {min(max_symbols, len(public))})")
        lines += [f"- `{s['file']}:{s['line']}` {s['kind']} `{s['qualname']}`" for s in public[:max_symbols]]
        return "\n".join(lines)


# --------------------------------------------------------------------------------------------- walking
def _git(root: Path, *args: str) -> str | None:
    try:
        r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, timeout=30,
                           encoding="utf-8", errors="replace")
        return r.stdout.strip() if r.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        return None


def list_files(root: Path) -> tuple[list[str], Counter]:
    """Repository-relative POSIX paths of analysable files; respects .gitignore when in a git repo."""
    skipped: Counter = Counter()
    listed = _git(root, "ls-files", "--cached", "--others", "--exclude-standard", "-z")
    if listed is not None and (root / ".git").exists():
        candidates = [p for p in listed.split("\0") if p]
    else:
        candidates = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in IGNORED_DIRS and not d.endswith(".egg-info")]
            rel_dir = Path(dirpath).relative_to(root)
            candidates += [(rel_dir / f).as_posix() for f in filenames]
    files = []
    for rel in sorted(set(candidates)):
        parts = PurePosixPath(rel).parts
        p = root / rel
        if any(part in IGNORED_DIRS or part.endswith(".egg-info") for part in parts[:-1]):
            skipped["ignored_dir"] += 1
        elif is_secret_file(p):
            skipped["secret"] += 1
        elif p.suffix.lower() in BINARY_SUFFIXES or rel.endswith((".min.js", ".map", "_pb2.py")):
            skipped["binary_or_generated"] += 1
        elif not p.is_file() or p.is_symlink():
            skipped["not_regular_file"] += 1
        elif p.stat().st_size > MAX_FILE_BYTES:
            skipped["too_large"] += 1
        else:
            files.append(rel)
    return files, skipped


def read_text(root: Path, rel: str) -> str | None:
    try:
        data = (root / rel).read_bytes()
    except OSError:
        return None
    if b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", errors="replace")


def fingerprint(root: Path, files: list[str]) -> str:
    h = hashlib.sha1(f"v{CACHE_VERSION}|{_git(root, 'rev-parse', 'HEAD')}".encode())
    for rel in files:
        st = (root / rel).stat()
        h.update(f"{rel}|{st.st_size}|{st.st_mtime_ns}\n".encode())
    return h.hexdigest()


def repo_identity(root: Path) -> tuple[str, str | None]:
    remote = _git(root, "config", "--get", "remote.origin.url")
    basis = remote or str(root.resolve()).lower()
    slug = re.sub(r"[^A-Za-z0-9]+", "-", (remote or root.resolve().name).rstrip("/").removesuffix(".git")
                  .split("/")[-1])[:40].strip("-") or "repo"
    return f"{slug}-{hashlib.sha1(basis.encode()).hexdigest()[:10]}", remote


# ------------------------------------------------------------------------------------- import graph
def _python_module_index(files: list[str]) -> dict[str, str]:
    index = {}
    for f in files:
        if not f.endswith(".py"):
            continue
        parts = list(PurePosixPath(f).with_suffix("").parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        for start in range(len(parts)):  # allow src/ layouts and nested roots
            if parts[start:]:
                index.setdefault(".".join(parts[start:]), f)
    return index


def _resolve_python(spec: str, src: str, modules: dict[str, str]) -> str | None:
    if spec.startswith("."):
        level = len(spec) - len(spec.lstrip("."))
        pkg = list(PurePosixPath(src).parent.parts)
        if level > 1:
            pkg = pkg[: len(pkg) - (level - 1)]
        rest = spec.lstrip(".")
        spec = ".".join(pkg + ([rest] if rest else []))
    return modules.get(spec)


def _resolve_js(spec: str, src: str, fileset: set[str]) -> str | None:
    if not spec.startswith("."):
        return None
    base = os.path.normpath(os.path.join(os.path.dirname(src), spec)).replace("\\", "/")
    for cand in [base] + [base + e for e in (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs")] + \
                [f"{base}/index{e}" for e in (".ts", ".tsx", ".js", ".jsx")]:
        if cand in fileset:
            return cand
    return None


# ------------------------------------------------------------------------------------ manifests etc.
def _load_toml(root: Path, rel: str) -> dict:
    if tomllib is None:
        return {}
    try:
        return tomllib.loads((root / rel).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _load_json(root: Path, rel: str) -> dict:
    try:
        value = json.loads((root / rel).read_text(encoding="utf-8"))
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def _detect_project_facts(root: Path, rm: RepoMap, file_texts: dict[str, str]) -> None:
    names = {PurePosixPath(f).name: f for f in rm.files}
    for f in rm.files:
        name = PurePosixPath(f).name
        if name in MANIFESTS and f.count("/") <= 1:
            rm.manifests[f] = MANIFESTS[name]
        if name.startswith("requirements") and name.endswith(".txt") and f.count("/") <= 1:
            rm.manifests[f] = "pip"
        if any(f.startswith(p) or f == p.rstrip("/") for p in CI_PATTERNS):
            rm.ci_files.append(f)
        if name in LINT_CONFIGS:
            rm.lint_tools.append(LINT_CONFIGS[name])
        if CONTRIB_PATTERNS.search(f):
            rm.contribution_docs.append(f)
    rm.package_managers = sorted(set(rm.manifests.values()) - {"python"} | ({"pip"} if "pyproject.toml" in rm.manifests else set()))

    deps_text = ""
    pyproject = _load_toml(root, "pyproject.toml") if "pyproject.toml" in rm.manifests else {}
    if pyproject:
        project = pyproject.get("project", {})
        rm.entry_points += [f"{k} = {v}" for k, v in project.get("scripts", {}).items()]
        deps_text += json.dumps(project.get("dependencies", [])) + json.dumps(project.get("optional-dependencies", {}))
        tool = pyproject.get("tool", {})
        deps_text += json.dumps(tool.get("poetry", {}).get("group", {})) + json.dumps(tool.get("poetry", {}).get("dev-dependencies", {}))
        for t in ("ruff", "black", "isort", "mypy", "pylint", "flake8"):
            if t in tool:
                rm.lint_tools.append(t)
        if "pytest" in tool or "pytest" in json.dumps(tool):
            rm.test_frameworks.append("pytest")
    for f, eco in rm.manifests.items():
        if eco in ("pip", "pipenv", "python") and f != "pyproject.toml":
            deps_text += file_texts.get(f) or read_text(root, f) or ""
    pkg = _load_json(root, "package.json") if "package.json" in rm.manifests else {}
    if pkg:
        scripts = pkg.get("scripts", {})
        rm.commands.update({f"npm run {k}": v for k, v in scripts.items() if isinstance(v, str)})
        if pkg.get("main"):
            rm.entry_points.append(f"package.json main: {pkg['main']}")
        bins = pkg.get("bin", {})
        rm.entry_points += [f"bin {k}: {v}" for k, v in (bins.items() if isinstance(bins, dict) else [])]
        all_deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
        for fw in ("jest", "vitest", "mocha", "ava", "jasmine"):
            if fw in all_deps or fw in json.dumps(scripts):
                rm.test_frameworks.append(fw)
        for t in ("eslint", "prettier", "typescript", "@biomejs/biome"):
            if t in all_deps:
                rm.lint_tools.append(t.split("/")[-1])
    if "Makefile" in names:
        text = read_text(root, names["Makefile"]) or ""
        for target in re.findall(r"^([A-Za-z][\w\-]*):", text, re.M)[:15]:
            rm.commands[f"make {target}"] = f"make {target}"
    if "tox.ini" in names:
        rm.commands["tox"] = "tox"

    rm.entry_points += [f for f in rm.files if f.endswith("__main__.py")]
    rm.entry_points += [f"{f} (__main__ guard)" for f, t in file_texts.items()
                        if f.endswith(".py") and "__name__" in t and re.search(r"if\s+__name__\s*==\s*['\"]__main__['\"]", t)][:15]

    rm.test_files = [f for f in rm.files if re.search(r"(^|/)(test_[^/]*\.py|[^/]*_test\.py|conftest\.py)$", f)
                     or re.search(r"\.(test|spec)\.[jt]sx?$", f) or "/__tests__/" in f"/{f}"]
    rm.test_dirs = sorted({str(PurePosixPath(f).parent) for f in rm.test_files})
    py_tests = [f for f in rm.test_files if f.endswith(".py")]
    if py_tests:
        uses_pytest = "pytest" in deps_text or any(n in names for n in ("conftest.py", "pytest.ini")) or \
            any("import pytest" in (file_texts.get(f) or "") for f in py_tests)
        uses_unittest = any("unittest" in (file_texts.get(f) or "") for f in py_tests)
        if uses_pytest:
            rm.test_frameworks.append("pytest")
        if uses_unittest:
            rm.test_frameworks.append("unittest")
        if not uses_pytest and not uses_unittest:
            rm.test_frameworks.append("pytest")  # plain test_*.py functions: pytest collects them
    rm.test_frameworks = sorted(set(rm.test_frameworks))
    rm.lint_tools = sorted(set(rm.lint_tools))
    if any(fw in rm.test_frameworks for fw in ("pytest", "unittest")):
        rm.test_command = ["python", "-m", "pytest"]  # pytest also runs unittest-style tests
    elif rm.test_frameworks and pkg.get("scripts", {}).get("test"):
        rm.test_command = ["npm", "test"]


# -------------------------------------------------------------------------------------------- build
def build_repo_map(root: Path, cache_dir: Path | None = None, use_cache: bool = True) -> RepoMap:
    root = root.resolve()
    if not root.is_dir():
        raise FileNotFoundError(f"repository not found: {root}")
    start = time.perf_counter()
    files, skipped = list_files(root)
    fp = fingerprint(root, files)
    repo_id, remote = repo_identity(root)
    cache_file = (cache_dir / repo_id / "repo_map.json") if cache_dir else None
    if use_cache and cache_file and cache_file.is_file():
        try:
            data = json.loads(cache_file.read_text(encoding="utf-8"))
            if data.get("fingerprint") == fp:
                rm = RepoMap(**data)
                rm.cache_hit, rm.build_seconds = True, round(time.perf_counter() - start, 3)
                return rm
        except (ValueError, TypeError):
            pass

    rm = RepoMap(root=str(root), repo_id=repo_id, head=_git(root, "rev-parse", "HEAD"),
                 branch=_git(root, "rev-parse", "--abbrev-ref", "HEAD"), remote=remote, fingerprint=fp,
                 skipped=dict(skipped))
    file_texts: dict[str, str] = {}
    indexes: dict[str, FileIndex] = {}
    lang_lines: Counter = Counter()
    total_chars = 0
    for rel in files:
        text = read_text(root, rel)
        if text is None:
            rm.skipped["binary_or_generated"] = rm.skipped.get("binary_or_generated", 0) + 1
            continue
        if any(marker in text[:600] for marker in GENERATED_MARKERS):
            rm.skipped["binary_or_generated"] = rm.skipped.get("binary_or_generated", 0) + 1
            continue
        rm.files.append(rel)
        file_texts[rel] = text
        total_chars += len(text)
        lang = LANGUAGES.get(PurePosixPath(rel).suffix.lower())
        if lang:
            lang_lines[lang] += text.count("\n") + 1
        idx = index_file(rel, text)
        if idx:
            indexes[rel] = idx
            if idx.parse_error:
                rm.parse_errors[rel] = idx.parse_error
    rm.languages = dict(lang_lines.most_common())
    rm.total_tokens_estimate = total_chars // 4

    modules = _python_module_index(rm.files)
    fileset = set(rm.files)
    for rel, idx in indexes.items():
        rm.symbols += [s.to_dict() for s in idx.symbols]
        targets = set()
        for spec in idx.imports:
            hit = _resolve_python(spec, rel, modules) if idx.language == "python" else _resolve_js(spec, rel, fileset)
            if hit and hit != rel:
                targets.add(hit)
        if targets:
            rm.imports[rel] = sorted(targets)
        if idx.string_literals:
            rm.string_literals[rel] = idx.string_literals[:300]
        top = PurePosixPath(rel).parts[0] if "/" in rel else "(root)"
        if top not in ("tests", "test", "docs"):
            rm.modules[top] = rm.modules.get(top, 0) + 1
    _detect_project_facts(root, rm, file_texts)
    rm.build_seconds = round(time.perf_counter() - start, 3)
    if cache_file:
        cache_file.parent.mkdir(parents=True, exist_ok=True)
        cache_file.write_text(rm.to_json(), encoding="utf-8")
    return rm
